"""View measured scaling studies without launching training or timing loops."""

import hashlib
import json
from pathlib import Path

import numpy as np
import streamlit as st
from matplotlib.figure import Figure


@st.cache_data(max_entries=4)
def read_results(path, signature):
    return json.loads(Path(path).read_text(encoding="utf8"))


@st.cache_data(max_entries=32, show_spinner=False)
def view_digest(path, signature):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def laboratory(root):
    st.header("HPC Laboratory")
    path = Path(
        st.text_input(
            "Benchmark results", str(root / "benchmarks" / "hpc-results.json")
        )
    )
    if not path.is_file():
        st.info("Choose a completed scaling report.")
        return
    rows = read_results(str(path.resolve()), path.stat().st_mtime_ns)["runs"]
    grid = st.selectbox("Grid width", sorted({r["grid"] for r in rows}))
    subset = [r for r in rows if r["grid"] == grid]
    methods = st.multiselect(
        "Methods",
        sorted({r["method"] for r in subset}),
        default=sorted({r["method"] for r in subset}),
    )
    subset = [r for r in subset if r["method"] in methods]
    if not subset:
        return
    group = st.selectbox("Evaluation group", sorted(subset[0]["groups"]))
    horizon = st.selectbox(
        "Rollout step",
        sorted(map(int, subset[0]["groups"][group]["horizons"])),
        index=3,
    )
    table = []
    for r in subset:
        g = r["groups"][group]
        m = g["horizons"][str(horizon)]
        table.append(
            {
                "run": r["run"],
                "method": r["method"],
                "device": r["device"],
                "rollout_ms": r["median_ms"],
                "relative_L2": m.get("relative_l2"),
                "mass_drift": m.get("abs_mass"),
                "energy_drift": m.get("abs_energy"),
                "peak_MiB": r["peak_mib"],
                "GPU_MiB": r["gpu_peak_mib"],
                "parameters": r["parameters"],
                "training_trajectories": r.get("training_count"),
                "finite": g["finite"],
                "minimum_depth_m": g["minimum_depth"],
            }
        )
    st.scatter_chart(table, x="rollout_ms", y="relative_L2", color="method")
    st.bar_chart(table, x="run", y="peak_MiB", color="device")
    st.dataframe(table)
    st.download_button(
        "Export selected benchmarks",
        json.dumps(subset),
        file_name="scaling.json",
        mime="application/json",
    )
    run = st.selectbox("Trajectory comparison", [r["run"] for r in subset])
    directory = Path(
        st.text_input(
            "Local trajectory directory", str(root / "outputs" / "hpc-v05" / "views")
        )
    )
    archive = directory / (Path(run).name + ".npz")
    if not archive.exists():
        st.caption("Local trajectory arrays are generated by the benchmark worker.")
        return
    expected = next(r.get("view_sha256") for r in subset if r["run"] == run)
    if expected != view_digest(
        str(archive.resolve()), (archive.stat().st_mtime_ns, archive.stat().st_size)
    ):
        st.info("The trajectory archive does not match this report.")
        return
    field = st.selectbox(
        "Physical field", ["Depth (m)", "East velocity (m/s)", "North velocity (m/s)"]
    )
    k = ("Depth (m)", "East velocity (m/s)", "North velocity (m/s)").index(field)
    with np.load(archive, allow_pickle=False) as data:
        a = data["reference"][horizon, k]
        b = data["prediction"][horizon, k]
        t = data["time_s"][horizon]
    fig = Figure(figsize=(7, 3), layout="constrained")
    lo, hi = min(a.min(), b.min()), max(a.max(), b.max())
    for ax, arr, title in zip(
        fig.subplots(1, 2), (a, b), ("MUSCL–MC", run), strict=True
    ):
        image = ax.imshow(
            arr, origin="lower", extent=(0, 200, 0, 200), vmin=lo, vmax=hi
        )
        ax.set(xlabel="x (km)", ylabel="y (km)", title=title)
        fig.colorbar(image, ax=ax)
    st.caption(f"First in-distribution trajectory · {t:g} s · {field}")
    st.pyplot(fig)
